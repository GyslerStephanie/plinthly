function resolve(key) {
  return key.split('.').reduce((o, k) => (o == null ? undefined : o[k]), COPY)
}

export function ut(key, vars) {
  let s = resolve(key)
  if (s == null) return key
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v))
  return s
}
